const fs = require('fs');
const path = require('path');
const db = require('../backend/db');
const { evaluateRegistrationFlags } = require('../backend/lib/kyc-flags');

async function main() {
  await db.init();
  const users = await db.getTable('users') || [];
  const stockists = users.filter(u => u.role === 'STOCKIST');

  let regFlags = await db.getTable('registration_flags');
  if (!regFlags) {
    regFlags = [];
  }

  const existingIds = new Set(regFlags.map(f => f.id));

  let totalProcessed = 0;
  const flagCounts = {};

  for (const user of stockists) {
    totalProcessed++;
    try {
      const flags = await evaluateRegistrationFlags(user, null, true); // isBackfill = true, IP = null
      for (const f of flags) {
        if (!existingIds.has(f.id)) {
          f.created_at = new Date().toISOString();
          regFlags.push(f);
          existingIds.add(f.id);

          flagCounts[f.flag_type] = (flagCounts[f.flag_type] || 0) + 1;
        }
      }
    } catch (e) {
      console.error(`Error processing user ${user.id}:`, e);
    }
  }

  await db.saveTable('registration_flags', regFlags);

  console.log(`\nBackfill complete. Processed ${totalProcessed} stockists.`);
  console.log('Flags generated by type:');
  for (const [type, count] of Object.entries(flagCounts)) {
    console.log(` - ${type}: ${count}`);
  }
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
